// Rewrites the clip table at the end of docs/VOICEOVER.md from the script, the clip
// metadata and the studio's Devanagari (tools/vo_devanagari.json). Safe to run again.
//   node tools/vo_docs.mjs [studio log json …]   (logs add/refresh Devanagari entries)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const script = JSON.parse(readFileSync(join(here, 'vo_script.json'), 'utf8'));
const meta = existsSync(join(here, 'vo_meta.json')) ? JSON.parse(readFileSync(join(here, 'vo_meta.json'), 'utf8')) : {};
const DEV = join(here, 'vo_devanagari.json');
const dev = existsSync(DEV) ? JSON.parse(readFileSync(DEV, 'utf8')) : {};

// harvest Devanagari from studio logs: match each script-step request to its spoken line
for (const f of process.argv.slice(2)) {
  const log = JSON.parse(readFileSync(f, 'utf8'));
  for (const c of log.calls || []) {
    if (!c.text || !c.request) continue;
    let req = c.request;
    try { req = JSON.parse(c.request).contents[0].parts[0].text; } catch { /* raw */ }
    const hit = script.filter((r) => req.includes(r.spoken)).sort((a, b) => b.spoken.length - a.spoken.length)[0];
    if (hit) dev[hit.id] = c.text.trim();
  }
}
writeFileSync(DEV, JSON.stringify(dev, null, 1) + '\n');

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const rows = script.map((r) => `| ${r.id} | ${cell(r.line)} | ${r.spoken === r.line ? '=' : cell(r.spoken)} | ${cell(dev[r.id] || '—')} | ${meta[r.id] ? meta[r.id].seconds.toFixed(2) : '—'} |`);
const table = ['| Clip | Line as shown | Spoken as | Devanagari sent to the voice | Seconds |', '|---|---|---|---|---|', ...rows].join('\n');

const DOC = join(root, 'docs', 'VOICEOVER.md');
const MARK = '<!-- CLIP TABLE (generated by tools/vo_docs.mjs) -->';
const doc = readFileSync(DOC, 'utf8');
const i = doc.indexOf(MARK);
writeFileSync(DOC, (i < 0 ? doc + '\n' : doc.slice(0, i)) + MARK + '\n\n' + table + '\n');
const total = script.reduce((s, r) => s + (meta[r.id]?.seconds || 0), 0);
console.log(`table: ${script.length} lines · ${(total / 60).toFixed(2)} min of audio · Devanagari for ${Object.keys(dev).length}`);
